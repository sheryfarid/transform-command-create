import { Fragment, useState } from 'react';
import type { EvidenceStatus } from '../../types/domain';
import { MANDATORY } from '../../features/reference';
import { assessmentState, gapsFor } from '../../features/inventory';
import { fmt, pct } from '../../features/utils';
import { useProgrammeStore, useScopedSystems } from '../../stores/programmeStore';
import { useProgrammeState } from '../../hooks/useProgramme';
import { Button, Chip, Empty, Gate, Section, StatusChip, useCan } from '../ui';

const ASSESSMENT_FLOW = ['Imported', 'Validation Required', 'In Assessment', 'Assessed', 'Baseline Approved'];
const EVIDENCE_FLOW = ['No evidence', 'Under review', 'Partial', 'Verified'];

function StateMachine({ label, states, extra }: { label: string; states: string[]; extra?: string }) {
  return (
    <div className="sm">
      <span className="sm-label">{label}</span>
      {states.map((x, i) => (
        <Fragment key={x}>{i > 0 && <span className="sm-arrow">›</span>}<span className="sm-node">{x}</span></Fragment>
      ))}
      {extra && <span className="sm-node bad">{extra}</span>}
    </div>
  );
}

export function DiscoveryPage() {
  const st = useProgrammeState();
  const systems = useScopedSystems();
  const { generateDiscoveryWork, answerQuestion, approveBaseline } = useProgrammeStore();
  const baselineGate = useCan('approveBaseline');
  const [answers, setAnswers] = useState<Record<string, { value?: string; status?: EvidenceStatus }>>({});

  if (!st.systems.length) {
    return <Empty title="No inventory to assess"><p>Discovery gaps are generated by comparing each record against the mandatory checklist. Import the inventory first.</p></Empty>;
  }

  const gaps = systems.flatMap(gapsFor);
  const open = st.questions.filter((q) => q.status === 'open');
  const done = st.questions.filter((q) => q.status === 'answered');
  const assessedNow = st.systems.filter((s) => assessmentState(s, st) === 'Assessed').length;
  const setAnswer = (id: string, patch: { value?: string; status?: EvidenceStatus }) => setAnswers({ ...answers, [id]: { ...answers[id], ...patch } });

  return (
    <div className="stack">
      <div className="grid-2">
        <Section title="Lifecycle">
          <p className="fine">Two independent state machines. Rejected or revoked evidence moves a fact back to review without deleting history.</p>
          <StateMachine label="Assessment" states={ASSESSMENT_FLOW} />
          <StateMachine label="Evidence" states={EVIDENCE_FLOW} extra="Disputed" />
        </Section>
        <Section title="Gaps against the mandatory checklist" aside={<Button kind="primary" onClick={generateDiscoveryWork} disabled={!gaps.length}>Generate discovery work</Button>}>
          <div className="dist">
            {MANDATORY.map((m) => {
              const n = gaps.filter((g) => g.field === m.key).length;
              return (
                <div key={m.key} className="dist-row">
                  <span>{m.label}</span>
                  <div className="bar"><i className="tone-warn" style={{ width: `${pct(n, systems.length)}%` }} /></div>
                  <b>{n}</b>
                </div>
              );
            })}
          </div>
          <p className="fine">{gaps.length} open gaps across {systems.length} systems in scope.</p>
        </Section>
      </div>

      <Section title={`Open questions (${open.length})`}>
        {!open.length && <p className="fine">No open questions. Generate discovery work from gaps, or create evidence requests from the strategy consultant.</p>}
        <div className="questions">
          {open.map((q) => {
            const a = answers[q.id] ?? {};
            return (
              <div key={q.id} className="question">
                <div className="row-wrap">
                  <Chip tone={q.category === 'Inventory gap' ? 'warn' : 'violet'}>{q.category}</Chip>
                  {q.severity && <span className="fine">{q.severity} priority</span>}
                  <span className="fine">Assigned to {q.owner}</span>
                </div>
                <p>{q.text}</p>
                <div className="row-wrap">
                  <input placeholder="Answer" value={a.value ?? ''} onChange={(e) => setAnswer(q.id, { value: e.target.value })} />
                  <select value={a.status ?? 'user_asserted'} onChange={(e) => setAnswer(q.id, { status: e.target.value as EvidenceStatus })}>
                    <option value="user_asserted">User asserted</option>
                    <option value="assumed">Assumed</option>
                    <option value="unknown">Unknown</option>
                  </select>
                  <Button small onClick={() => answerQuestion(q.id, (a.value ?? '').trim(), a.status ?? 'user_asserted')}>Submit answer</Button>
                </div>
              </div>
            );
          })}
        </div>
        {done.length > 0 && (
          <details className="answered">
            <summary>Answered ({done.length})</summary>
            {done.map((q) => <div key={q.id} className="line">{q.answerStatus && <StatusChip status={q.answerStatus} />}<span>{q.text} <b>{q.answer}</b></span></div>)}
          </details>
        )}
      </Section>

      <Section
        title="Discovered baseline"
        aside={<Button kind="primary" disabled={!baselineGate.allowed || !assessedNow} title={baselineGate.title} onClick={approveBaseline}>Approve baseline v{st.baselines.length + 1}</Button>}
      >
        <Gate perm="approveBaseline" />
        <p className="fine">Freezes a versioned snapshot of the {assessedNow} currently assessed systems and sends it to strategy analysis. Systems with open gaps stay out of the baseline.</p>
        {st.baselines.map((b) => (
          <div key={b.version} className="line">
            <Chip tone="ok">v{b.version}</Chip>
            <span>{b.systemIds.length} of {b.total} systems, {b.verifiedPct}% of mandatory fields verified. Approved by {b.by}, {fmt(b.at)}.</span>
          </div>
        ))}
      </Section>
    </div>
  );
}
